-- 04_themes.sql
-- Creates the themes and word_themes tables and fills them with the cheat sheet's 30 themes.
-- A word can belong to several themes. Both tables are read-only for app users.
-- Run 03_add_cheatsheet_words.sql first. Safe to run more than once.

create table if not exists "French-schema".themes (
    id          integer primary key,
    title       text not null,
    group_name  text,
    level       text,
    sort_order  integer,
    source      text default 'cheatsheet',
    created_at  timestamptz default now()
);

create table if not exists "French-schema".word_themes (
    theme_id    integer not null references "French-schema".themes(id) on delete cascade,
    word_id     bigint  not null,
    sort_order  integer,
    primary key (theme_id, word_id)
);
create index if not exists word_themes_word_id_idx on "French-schema".word_themes (word_id);

-- Link word_themes.word_id to vocabulary_bank.id when id is unique (it normally is).
do $$
begin
    if not exists (select 1 from pg_constraint where conname = 'word_themes_word_id_fkey')
       and exists (select 1 from pg_index i join pg_attribute a on a.attrelid = i.indrelid and a.attnum = any(i.indkey)
                   where i.indrelid = '"French-schema".vocabulary_bank'::regclass and i.indisunique and a.attname = 'id' and array_length(i.indkey::int2[], 1) = 1)
    then
        alter table "French-schema".word_themes
            add constraint word_themes_word_id_fkey foreign key (word_id) references "French-schema".vocabulary_bank(id) on delete cascade;
    end if;
end $$;

-- Anyone using the app can read themes; nobody can change them through the app.
alter table "French-schema".themes enable row level security;
alter table "French-schema".word_themes enable row level security;
drop policy if exists "Themes are readable by everyone" on "French-schema".themes;
create policy "Themes are readable by everyone" on "French-schema".themes for select using (true);
drop policy if exists "Theme words are readable by everyone" on "French-schema".word_themes;
create policy "Theme words are readable by everyone" on "French-schema".word_themes for select using (true);
grant select on "French-schema".themes, "French-schema".word_themes to anon, authenticated;

