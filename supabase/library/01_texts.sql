-- 01_texts.sql
-- The shared library of Reading and Listening texts. Every text the AI writes for a student is
-- saved here, so the next student at that level can use it without spending an AI use.
-- Students can read every text and add their own AI texts; only admins can change or remove them.
-- Safe to run more than once; it removes nothing.

create table if not exists "French-schema".library_texts (
    id         bigint generated by default as identity primary key,
    level      text        not null check (level in ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),
    subject    text,
    kind       text,                                       -- article, story, dialogue, email…
    title      text        not null check (char_length(title) <= 120),
    fr         text        not null check (char_length(fr) between 40 and 6000),   -- the French text
    en         text        check (char_length(en) <= 7000),                        -- English translation
    questions  jsonb       not null default '[]'::jsonb,   -- [{ q, options: [...], answer, why }]
    created_by uuid        default auth.uid(),
    created_at timestamptz not null default now()
);

create index if not exists library_texts_level on "French-schema".library_texts (level, created_at desc);

alter table "French-schema".library_texts enable row level security;
do $$
begin
    if not exists (select 1 from pg_policies where schemaname = 'French-schema' and tablename = 'library_texts' and policyname = 'Signed-in users read the library') then
        create policy "Signed-in users read the library" on "French-schema".library_texts
            for select to authenticated using (true);
    end if;
    if not exists (select 1 from pg_policies where schemaname = 'French-schema' and tablename = 'library_texts' and policyname = 'Students add their own texts') then
        create policy "Students add their own texts" on "French-schema".library_texts
            for insert to authenticated with check (created_by = auth.uid());
    end if;
end $$;

revoke all on "French-schema".library_texts from anon, authenticated;
grant select, insert on "French-schema".library_texts to authenticated;

