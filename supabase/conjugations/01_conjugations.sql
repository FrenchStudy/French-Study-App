-- 01_conjugations.sql
-- Conjugation tables kept in the database, so the app can conjugate any verb and find a verb from any
-- of its forms (mangeons, ai mangé, irons) without AI. Two tables:
--   conjugation_verbs  one row per verb (about 2,060, with the reflexive ones): the tables as JSON
--   conjugation_forms  one row per form, built from conjugation_verbs by 03_forms.sql, for searching
-- Students can read both; nobody can change them from the app (edit them in Table Editor).
-- Safe to run more than once; it removes nothing.

-- Lower-case and without accents, so "etre" finds "être" and "mange" finds "mangé" (also used by the app's search)
create or replace function "French-schema".plain_text(t text) returns text
language sql immutable as $$
    select lower(translate(replace(replace(coalesce($1, ''), 'œ', 'oe'), 'æ', 'ae'),
                           'àâäáãÀÂÄÁÃéèêëÉÈÊËíìîïÍÌÎÏóòôöõÓÒÔÖÕúùûüÚÙÛÜýÿç',
                           'aaaaaaaaaaeeeeeeeeiiiiiiiioooooooooouuuuuuuuyyc'))
$$;

create table if not exists "French-schema".conjugation_verbs (
    inf        text primary key,                            -- infinitive: manger, se laver, s'habiller
    english    text,                                        -- meaning, from vocabulary.csv
    ending     text    not null check (ending in ('er', 'ir', 're', 'oir')),
    grp        smallint not null check (grp in (1, 2, 3)),  -- 1 = -er, 2 = -ir like finir, 3 = everything else
    pronominal boolean not null default false,              -- reflexive: se laver
    aux        text    not null check (aux in ('avoir', 'être')),
    pp         text    not null,                            -- past participle
    forms      jsonb   not null,                            -- { p, im, f, c, s: six forms; ip: tu, nous, vous }
    note       text
);

create table if not exists "French-schema".conjugation_forms (
    id         bigint generated by default as identity primary key,
    inf        text     not null references "French-schema".conjugation_verbs (inf) on delete cascade,
    tense      text     not null,     -- present, imparfait, futur, conditionnel, subjonctif, imperatif, participe_passe
    person     text     not null,     -- je, tu, il/elle, nous, vous, ils/elles ('' for the participle)
    form       text     not null,
    form_plain text     not null      -- form without accents, lower case: what the search compares
);

create index if not exists conjugation_forms_plain on "French-schema".conjugation_forms (form_plain);
create index if not exists conjugation_forms_inf on "French-schema".conjugation_forms (inf);
create index if not exists conjugation_verbs_plain on "French-schema".conjugation_verbs ("French-schema".plain_text(inf));

alter table "French-schema".conjugation_verbs enable row level security;
alter table "French-schema".conjugation_forms enable row level security;
do $$
begin
    if not exists (select 1 from pg_policies where schemaname = 'French-schema' and tablename = 'conjugation_verbs' and policyname = 'Signed-in users read conjugation verbs') then
        create policy "Signed-in users read conjugation verbs" on "French-schema".conjugation_verbs
            for select to authenticated using (true);
    end if;
    if not exists (select 1 from pg_policies where schemaname = 'French-schema' and tablename = 'conjugation_forms' and policyname = 'Signed-in users read conjugation forms') then
        create policy "Signed-in users read conjugation forms" on "French-schema".conjugation_forms
            for select to authenticated using (true);
    end if;
end $$;

revoke all on "French-schema".conjugation_verbs from anon, authenticated;
revoke all on "French-schema".conjugation_forms from anon, authenticated;
grant select on "French-schema".conjugation_verbs to authenticated;
grant select on "French-schema".conjugation_forms to authenticated;
grant execute on function "French-schema".plain_text(text) to authenticated;

-- Check: both tables exist and are empty until you run the next files
select (select count(*) from "French-schema".conjugation_verbs) as verbs,
       (select count(*) from "French-schema".conjugation_forms) as forms;
